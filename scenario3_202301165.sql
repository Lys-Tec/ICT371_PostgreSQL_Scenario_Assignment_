CREATE OR REPLACE PROCEDURE hostel_lab.show_full_or_nearly_full_rooms()
LANGUAGE plpgsql
AS $$
DECLARE
    v_room record;
    c_low CURSOR FOR
        SELECT room_name, available_beds
        FROM hostel_lab.hostel_rooms
        WHERE available_beds <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_room;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% beds remaining)',
            v_room.room_name, v_room.available_beds;
    END LOOP;
    CLOSE c_low;
END;
$$;

