
DROP SCHEMA IF EXISTS hostel_lab CASCADE;
CREATE SCHEMA hostel_lab;
SET search_path TO hostel_lab, public;

CREATE TABLE hostel_rooms (
    room_id integer PRIMARY KEY,
    room_name text NOT NULL,
    available_beds integer NOT NULL CHECK (available_beds >= 0)
);

CREATE TABLE allocations (
    allocation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id integer NOT NULL REFERENCES hostel_rooms(room_id),
    student_number text NOT NULL,
    status text NOT NULL CHECK (status IN ('ACTIVE', 'CHECKED_OUT'))
);

