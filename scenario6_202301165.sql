CREATE OR REPLACE PROCEDURE event_lab.show_full_or_nearly_full_events()
LANGUAGE plpgsql
AS $$
DECLARE
    v_event record;
    c_low CURSOR FOR
        SELECT event_name, available_seats
        FROM event_lab.events
        WHERE available_seats <= 2
        ORDER BY event_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_event;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% seats remaining)',
            v_event.event_name, v_event.available_seats;
    END LOOP;
    CLOSE c_low;
END;
$$;

