CREATE OR REPLACE PROCEDURE event_lab.cancel_booking(p_booking_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_event_id integer;
    v_seats integer;
BEGIN
    SELECT event_id, seats
    INTO v_event_id, v_seats
    FROM event_lab.bookings
    WHERE booking_id = p_booking_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active booking with ID %', p_booking_id;
        RETURN;
    END IF;

    UPDATE event_lab.bookings
    SET status = 'CANCELLED' WHERE booking_id = p_booking_id;

    UPDATE event_lab.events
    SET available_seats = available_seats + v_seats
    WHERE event_id = v_event_id;

    RAISE NOTICE 'Booking % cancelled; % seats released', p_booking_id, v_seats;
END;
$$;

